import turtle

t = turtle.Turtle()   # Crea una tortuga
t.forward(100)        # Avanza 100 unidades
t.right(90)          # Gira 90 grados a la derecha
t.forward(100)        # avanza 100 pasos
t.left(90)            # girada 90 grados
t.forward(100)        # avanza 100 pasos
t.right(90)           # gira 90 grados
t.forward(100)        # avanza 100 pasos
t.left(90)            # gira 90 grados
t.forward(100)        # avanza 100 pasos
turtle.done()         # Mantiene la ventana 
